export type TranslationKey = keyof typeof en;
export type Dict = Record<TranslationKey, string>;

// English is built in; the others are loaded when first needed, so a page
// doesn't carry four dictionaries. Until one has loaded, translate() falls
// back to English.
const DICTS: Partial<Record<Language, Dict>> = { en };
const LOADERS: Record<Exclude<Language, 'en'>, () => Promise<{ default: Dict }>> = {
  fr: () => import('./locales/fr'),
  es: () => import('./locales/es'),
  de: () => import('./locales/de'),
};
const loading: Partial<Record<Language, Promise<void>>> = {};

export function languageLoaded(language: Language): boolean {
  return !!DICTS[language];
}

export function loadLanguage(language: Language): Promise<void> {
  if (DICTS[language] || language === 'en') return Promise.resolve();
  return (loading[language] ??= LOADERS[language]().then((m) => { DICTS[language] = m.default; }, () => { delete loading[language]; }));
}

const PLURAL_RULES: Partial<Record<Language, Intl.PluralRules>> = {};

function pluralCategory(language: Language, n: number): Intl.LDMLPluralRule {
  const rules = (PLURAL_RULES[language] ??= new Intl.PluralRules(LOCALE_MAP[language]));
  return rules.select(n);
}

/**
 * Looks up a string and fills in {placeholders}.
 * Inline plural forms are written as {count|one|other}: the form is chosen
 * with Intl.PluralRules.
 */
export function translate(language: Language, key: TranslationKey, vars?: Record<string, string | number>): string {
  let str = DICTS[language]?.[key] ?? en[key] ?? key;
  if (vars) {
    str = str.replace(/\{(\w+)\|([^}]+)\}/g, (match: string, name: string, body: string) => {
      const raw = vars[name];
      if (raw === undefined) return match;
      const forms = body.split('|');
      // A count passed already formatted ("4 101 238", "1,234") still picks
      // its form by value: drop group separators before reading it.
      const n = typeof raw === 'number' ? raw : Number(String(raw).replace(/[\s  '’]|[.,](?=\d{3}(?:\D|$))/g, '').replace(',', '.'));
      const cat = pluralCategory(language, Number.isFinite(n) ? n : 0);
      const idx = forms.length >= 3 ? (cat === 'one' ? 0 : cat === 'few' ? 1 : 2) : cat === 'one' ? 0 : 1;
      return forms[idx] ?? forms[forms.length - 1];
    });
    for (const [k, v] of Object.entries(vars)) {
      str = str.split(`{${k}}`).join(String(v));
    }
  }
  return str;
}

// Pages that live outside AppProvider (invite, public profile) have no
// account language to read: pick the first supported language from the
// browser's list (navigator.languages) or an Accept-Language header.
export function pickLanguage(candidates: readonly string[] | string | null | undefined): Language {
  const list = typeof candidates === 'string'
    ? candidates.split(',').map((part) => part.split(';')[0].trim())
    : candidates ?? [];
  for (const c of list) {
    const base = c.toLowerCase().split('-')[0];
    if ((LANGUAGES as readonly string[]).includes(base)) return base as Language;
  }
  return 'en';
}

export function pluralForKey(language: Language, n: number, one: TranslationKey, few: TranslationKey, many: TranslationKey): string {
  void few; // a form some languages had; the supported ones use one/other
  const cat = pluralCategory(language, n);
  return cat === 'one' ? translate(language, one) : translate(language, many);
}

// Region codes for the profile's region picker. Falls back to a curated
// list if the runtime doesn't support Intl.supportedValuesOf (older Node).
export function getRegionCodes(): string[] {
  try {
    const supportedValuesOf = Intl.supportedValuesOf as ((key: string) => string[]) | undefined;
    if (typeof supportedValuesOf === 'function') {
      return supportedValuesOf('region').filter((r: string) => /^[A-Z]{2}$/.test(r));
    }
  } catch {
    // fall through to curated list
  }
  return ['US', 'GB', 'RU', 'DE', 'FR', 'ES', 'IT', 'BR', 'MX', 'JP', 'KR', 'IN', 'CA', 'AU', 'NL', 'SE', 'PL', 'TR', 'UA', 'PT'];
}

const LOCALE_MAP: Record<Language, string> = {
  en: 'en-US', fr: 'fr-FR', es: 'es-ES', de: 'de-DE',
};

export function toLocale(language: Language): string {
  return LOCALE_MAP[language];
}

export function regionDisplayName(code: string, language: Language): string {
  try {
    return new Intl.DisplayNames([language], { type: 'region' }).of(code) ?? code;
  } catch {
    return code;
  }
}

// Quotation marks of the interface language around a quote (reviews, the
// recap line): «…» es, « … » fr, „…“ de, “…” en.
export function quoted(language: Language, text: string): string {
  switch (language) {
    case 'es':
      return `«${text}»`;
    case 'fr':
      return `« ${text} »`;
    case 'de':
      return `„${text}“`;
    default:
      return `“${text}”`;
  }
}

// A language from storage (an account, a push subscription): one the site
// supports, else English (Russian accounts from before it was removed).
export function normalizeLanguage(value: unknown): Language {
  return typeof value === 'string' && (LANGUAGES as readonly string[]).includes(value) ? (value as Language) : 'en';
}
